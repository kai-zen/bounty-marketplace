/**
 * Writes ABIs for BountyFactory, BountyEscrow, and SubmissionRegistry to `abis/`.
 *
 * Each contract gets a JSON file and a TypeScript module (`as const`) so
 * `@bounty/types/contracts` can re-export a wagmi-compatible ABI. Both are
 * committed. Full Hardhat artifacts under `artifacts/` stay gitignored.
 * `pnpm compile` runs this after `hardhat compile`; `pnpm export-abis` compiles
 * if needed, then writes the same files.
 */
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { artifacts } from "hardhat";

const CONTRACTS = [
  "BountyFactory",
  "BountyEscrow",
  "SubmissionRegistry",
] as const;

const packageRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const outDir = path.join(packageRoot, "abis");

await mkdir(outDir, { recursive: true });

for (const name of CONTRACTS) {
  const { abi } = await artifacts.readArtifact(name);
  const jsonPath = path.join(outDir, `${name}.json`);
  const tsPath = path.join(outDir, `${name}.ts`);
  const json = JSON.stringify(abi, null, 2);
  const exportName = `${name[0].toLowerCase()}${name.slice(1)}Abi`;

  await writeFile(jsonPath, `${json}\n`);
  await writeFile(
    tsPath,
    `/** Generated by scripts/export-abis.ts. Do not edit. */\nimport type { Abi } from "viem";\n\nexport const ${exportName} = ${json} as const satisfies Abi;\n`,
  );
  console.log(`exported ${name} -> abis/${name}.json, abis/${name}.ts`);
}
